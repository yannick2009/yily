// Mapping of language codes to locale strings for formatting dates, numbers, and other locale-sensitive data. This is used in the `locale` function to return the appropriate locale string based on the current language code.
const LOCALES: Record<LangCode, string> = {
  en: "en-US",
  fr: "fr-FR",
  es: "es-ES",
  de: "de-DE",
  it: "it-IT",
  pt: "pt-PT",
  ru: "ru-RU",
  zh: "zh-CN",
  ja: "ja-JP",
  ko: "ko-KR",
};

// locale function that returns the current locale string based on the current language code. This is useful for formatting dates, numbers, and other locale-sensitive data in the application.
export function locale(): string {
  return LOCALES[lang()];
}

// Translation function that retrieves the appropriate message based on the current language and key, and replaces any parameters in the message.
// If the message is not found in the current language, it falls back to English. If it's not found in English either, it returns the key itself.
export function t(
  key: string,
  params?: Record<string, string | number>,
): string {
  let s = messages[lang()][key] ?? messages.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

// Pluralization function that handles Russian pluralization rules
export function plural(key: string, count: number): string {
  if (lang() === "ru") return t(`${key}.${ruPlural(count)}`, { count });
  return t(count === 1 ? `${key}.one` : `${key}.other`, { count });
}

// Russian pluralization rules
function ruPlural(count: number): "one" | "few" | "many" {
  const n = Math.abs(count) % 100;
  const n1 = n % 10;
  if (n > 10 && n < 20) return "many";
  if (n1 > 1 && n1 < 5) return "few";
  if (n1 === 1) return "one";
  return "many";
}
