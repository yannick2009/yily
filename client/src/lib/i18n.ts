// Minimal i18n module: flat keys, 10 languages, t() / plural() helpers.
import { createSignal } from "solid-js";

// Key used to store the selected language in localStorage
const STORAGE_KEY = "yily-lang";

// Supported language codes for the application. These codes are used to identify the language in which the application should be displayed.
export type LangCode =
  | "en"
  | "fr"
  | "es"
  | "de"
  | "it"
  | "pt"
  | "ru"
  | "zh"
  | "ja"
  | "ko";

// Interface representing a language supported by the application. It includes the language code, the native name of the language, and the English name of the language.
export interface Language {
  code: LangCode;
  native: string;
  english: string;
}

// List of supported languages in the application.
export const LANGUAGES: Language[] = [
  { code: "en", native: "English", english: "English" },
  { code: "fr", native: "Français", english: "French" },
  { code: "es", native: "Español", english: "Spanish" },
  { code: "de", native: "Deutsch", english: "German" },
  { code: "it", native: "Italiano", english: "Italian" },
  { code: "pt", native: "Português", english: "Portuguese" },
  { code: "ru", native: "Русский", english: "Russian" },
  { code: "zh", native: "中文", english: "Chinese (Simplified)" },
  { code: "ja", native: "日本語", english: "Japanese" },
  { code: "ko", native: "한국어", english: "Korean" },
];

// Function to read the stored language from localStorage.
function readStored(): LangCode {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (LANGUAGES.some((l) => l.code === v)) return v as LangCode;
  } catch {
    /* localStorage unavailable */
  }
  return "en";
}

const initial = readStored();
document.documentElement.lang = initial;

// Reactive language signal shared across the app.
export const [lang, setLang] = createSignal<LangCode>(initial);

// Function to apply a new language setting. It updates the document's language attribute, stores the new language in localStorage, and updates the reactive signal for the current language.
export function applyLang(next: LangCode): void {
  document.documentElement.lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* localStorage unavailable */
  }
  setLang(next);
}

